"""Declarative spec for the synthetic, enum-rich tool environment.

Motivation: the three real benchmarks (BFCL / tau2 / AppWorld) have *few*
enumerable arguments, so the coarse<->fine granularity sweep (which lives or dies
on baking enum values into function names) is shallow. This synthetic env is
purpose-built for granularity: every domain is full of small CLOSED value sets
(window positions, light zones, HVAC modes, ...), so each native function expands
into many name-baked functions at the fine extreme and collapses into one
`execute(operation, ...)` at the coarse extreme.

Realism note: a domain is *not* just enums. To match the density of the real
benchmarks (tau2 retail/airline carry ~14-16 functions per domain at ~2.5 args
each) every domain here carries (a) ~15+ sibling functions -- including
fine-grained / closely-related ones inspired by real device & web APIs (Home
Assistant services, Spotify player, Google Calendar, automotive cabin, ...) --
and (b) a healthy share of NON-enumerable arguments: integer quantities (NUM,
e.g. transition seconds, levels, temperatures) and free-text grounding strings
(STR, e.g. titles, names, codes). NUM/STR are NOT bakeable into names, so they
stay as real arguments at every granularity, keeping even the fully-fine schema
non-trivial. Most functions take 2-3 arguments.

Single source of truth. From `DOMAINS` we derive (see `build.py`):
  - `data/synthetic/tools.json`  : grouped canonical schemas (group = domain),
    consumed unchanged by `schema_variants.py` / `schema_adapter.py`.
  - `data/synthetic/queries.jsonl`: NL tasks with programmatic GOLD calls.

A *domain* = {name, title, system, tools[], scenarios[]}.
A *tool*   = T(name, desc, params, templates, phrases):
  - params : ordered dict param -> spec. Helpers:
      E(desc,*vals)        closed enum (string)  -> BAKEABLE into names
      BOOL(desc)           boolean               -> BAKEABLE into names
      NUM(desc,lo,hi,..)   integer (continuous)  -> NOT bakeable, stays an arg
      STR(desc,*pool)      free string (grounding)-> NOT bakeable, stays an arg
  - templates: NL strings. `{p_x}` -> a surface phrase for param `p`'s sampled
    value (from `phrases`); `{p}` -> the raw sampled value. EVERY param must
    appear in every template so the gold value is recoverable from the text.
  - phrases : param -> {value(str) -> [surface phrases]}. Booleans key on
    "true"/"false".
A *scenario* (multi-call) = {templates, calls:[(tool, args), ...]} with fixed
args, for the compositional tasks within a single domain.
"""

# --------------------------------------------------------------------------- #
# param helpers
# --------------------------------------------------------------------------- #
def E(desc, *vals):
    return {"type": "string", "enum": list(vals), "description": desc}

def BOOL(desc):
    return {"type": "boolean", "description": desc}

def NUM(desc, lo, hi, samples=None):
    return {"type": "integer", "description": desc, "_range": (lo, hi),
            "_samples": list(samples) if samples else None}

def STR(desc, *pool):
    return {"type": "string", "description": desc, "_pool": list(pool)}

def T(name, desc, params, templates, phrases=None):
    return {"name": name, "description": desc, "params": params,
            "templates": templates, "phrases": phrases or {}}


# --------------------------------------------------------------------------- #
# compound-routine helpers (tau-bench-style multi-step compositional tasks)
# --------------------------------------------------------------------------- #
def S(slot):
    """Reference a sampled slot value inside a routine's gold call args."""
    return {"__slot__": slot}

def R(name, templates, calls, slots=None, phrases=None, kind="compound"):
    """A multi-step routine: a high-level NL intent decomposing into several gold
    calls. `slots` (name -> list of values) are sampled to produce instances;
    `{slot}` / `{slot_p}` render the raw value / a surface phrase (from `phrases`);
    `S("slot")` in a call arg binds it.

    `kind` distinguishes the two complexity tiers:
      - "compound"      : several INDEPENDENT calls on different subsystems, in
                          one request (breadth; order does not matter).
      - "compositional" : a DEPENDENT chain that builds up ONE entity step by
                          step (depth; a created/identified entity threads through
                          later calls, e.g. create event -> configure it -> invite
                          to it -> remind about it)."""
    return {"name": name, "templates": templates, "calls": calls,
            "slots": slots or {}, "phrases": phrases or {}, "kind": kind}


